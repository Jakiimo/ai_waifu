def prompt_key(messages):
    from prepare_data import normalize
    return "\n".join(message["role"] + ":" + normalize(message["content"]) for message in messages)


from training_data import encode_conversation


def main():
    if OUT.exists():
        raise SystemExit("傲娇 v2 已存在；请先保留原候选版本，不自动覆盖抽查记录。")
    old = read_jsonl(ROOT / "history" / "m2_persona_v1" / "data" / "m2" / "raw_cards.jsonl")
    revised = []
    counts = Counter()
    for card in old:
        answers = [line.strip() for line in ANSWERS[card["category"]].strip().splitlines() if line.strip()]
        assert len(answers) == 25
        index = counts[card["category"]]
        counts[card["category"]] += 1
        revised.append({**card, "family_id": "v2-" + card["family_id"], "assistant": answers[index],
                        "review": "ai_authored_style_revision_human_pending", "history": []})
    for i, (question, first_reply, variants, target) in enumerate(DIALOGUES, 1):
        revised.append({"family_id": f"v2-train-relationship-{i:02d}", "category": "relationship",
            "user_variants": variants, "assistant": target,
            "history": [{"role": "user", "content": question}, {"role": "assistant", "content": first_reply}],
            "source": "project_authored_ai_assisted", "review": "ai_authored_style_revision_human_pending"})
    rows, seen = [], set()
    for card in revised:
        for i, user in enumerate(card["user_variants"], 1):
            messages = card["history"] + [{"role": "user", "content": user}, {"role": "assistant", "content": card["assistant"]}]
            key = prompt_key(messages[:-1])
            if key in seen:
                raise ValueError("新候选版本输入重复，需检查场景。")
            seen.add(key)
            rows.append({"id": f"{card['family_id']}-v{i}", "family_id": card["family_id"],
                         "category": card["category"], "source": card["source"], "review": card["review"], "messages": messages})
    # 复现首次候选快照时的检查口径：使用归档v1留出的输入筛查单轮泄漏。
    # 当前主流程的完整上下文检查与新版开发评测由 prepare_data.py / scripts/m2.py 完成。
    # 多轮样本单独记录，并按完整上下文查完全重复；字符筛查仅是线索。
    dev = read_jsonl(ROOT / "history" / "m2_persona_v1" / "data" / "m2" / "dev_scenarios.jsonl")
    tests = read_jsonl(ROOT / "history" / "m2_persona_v1" / "data" / "test_scenarios.jsonl")
    isolation = check_isolation([r for r in rows if len(r["messages"]) == 2], dev, tests, 0.65)
    heldout = {prompt_key(c["messages"]) for c in dev + tests}
    if any(prompt_key(r["messages"][:-1]) in heldout for r in rows):
        raise ValueError("候选数据与开发或测试上下文完全重复。")
    from transformers import AutoTokenizer
    tokenizer = AutoTokenizer.from_pretrained(ROOT / "models" / "qwen2.5-1.5b-instruct", local_files_only=True)
    system_prompt = "你是凛音，一位嘴硬心软的成年虚构女性，与用户是熟悉的同伴。用自然的中文接话，平时轻轻拌嘴，关心时认真，不用固定口癖，也不编造事实。"
    token_checks = []
    for row in rows:
        encoded, report = encode_conversation(tokenizer, system_prompt, row["messages"], 256)
        assert any(token != -100 for token in encoded["labels"])
        token_checks.append({"id": row["id"], **report})
    OUT.mkdir(parents=True)
    def write_jsonl(name, records):
        (OUT / name).write_text("".join(json.dumps(record, ensure_ascii=False) + "\n" for record in records), encoding="utf-8")
    write_jsonl("raw_cards.jsonl", revised)
    write_jsonl("train_candidate.jsonl", rows)
    (OUT / "short_prompt.txt").write_text(system_prompt + "\n", encoding="utf-8")
    # 每类 6 个不同场景，抽查 30 条；一族只取一种问法，避免重复占抽查名额。
    selected = []
    rng = random.Random(42)
    for category in sorted(ANSWERS.keys() | {"relationship"}):
        candidates = [r for r in rows if r["category"] == category and r["id"].endswith("-v1")]
        selected.extend(rng.sample(candidates, 6))
    selected.sort(key=lambda r: (r["category"], r["id"]))
    with (OUT / "review_samples.csv").open("w", encoding="utf-8-sig", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=["id", "category", "history", "user", "assistant", "human_verdict", "notes"])
        writer.writeheader()
        for row in selected:
            writer.writerow({"id": row["id"], "category": row["category"],
                "history": " / ".join(m["role"] + ": " + m["content"] for m in row["messages"][:-2]),
                "user": row["messages"][-2]["content"], "assistant": row["messages"][-1]["content"],
                "human_verdict": "pending", "notes": ""})
    lines = ["# 傲娇 v2 台词抽查", "", "30 个不同场景，含已有上下文；全部是原创候选目标回答，不是模型生成效果。", ""]
    for row in selected:
        lines.extend([f"## {row['id']}", ""])
        if len(row["messages"]) > 2:
            lines.extend(["前文：", ""] + [f"- {m['role']}：{m['content']}" for m in row["messages"][:-2]] + [""])
        lines.extend(["用户：" + row["messages"][-2]["content"], "", "凛音：" + row["messages"][-1]["content"], "", "人工意见：待填写。", ""])
    (OUT / "review_samples.md").write_text("\n".join(lines), encoding="utf-8")
    summary = {"version": "m2-tsundere-v2-candidate", "status": "style_revision_not_frozen",
        "training_examples": len(rows), "scene_families": len(revised), "unique_target_answers": len({r['messages'][-1]['content'] for r in rows}),
        "single_turn_examples": sum(len(r["messages"]) == 2 for r in rows),
        "contextual_examples": sum(len(r["messages"]) > 2 for r in rows),
        "review_scenarios": len(selected), "human_review": "pending",
        "max_training_tokens": max(r["prompt_tokens"] + r["answer_tokens"] for r in token_checks),
        "single_turn_isolation": isolation,
        "multi_turn_check": "完整上下文无完全重复；未宣称完成全量语义近重复人工审核。",
        "token_checks": token_checks,
        "files": {name: digest(OUT / name) for name in ["raw_cards.jsonl", "train_candidate.jsonl", "short_prompt.txt"]},
        "source": "AI-assisted original dialogue; research references not copied into corpus",
        "training": "not_run", "prompt_selection": "not_run", "old_frozen_version": "preserved"}
    dump_json(OUT / "validation_report.json", summary)
    print(json.dumps({k: summary[k] for k in ['status', 'training_examples', 'scene_families', 'single_turn_examples', 'contextual_examples', 'review_scenarios', 'max_training_tokens', 'human_review']}, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
