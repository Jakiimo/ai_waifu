def build():
    rows = []
    for split, bank, count in [('train', TRAIN, 30), ('dev', DEV, 5), ('test', TEST, 10)]:
        parsed = {}
        for category in CATEGORIES:
            lines = [line.strip() for line in bank[category].strip().splitlines() if line.strip()]
            assert len(lines) == count, (split, category, len(lines))
            parsed[category] = lines
        for index in range(count):
            for category in CATEGORIES:
                parts = parsed[category][index].split('|')
                assert len(parts) in (2, 4)
                messages = [] if len(parts) == 2 else [
                    {'role': 'user', 'content': parts[2]}, {'role': 'assistant', 'content': parts[3]}]
                messages.append({'role': 'user', 'content': parts[0]})
                name = f'm6-{split}-{category}-{index + 1:02}'
                rows.append({'id': name, 'family_id': name, 'split': split, 'category': category,
                             'messages': messages, 'expectation': parts[1],
                             'data_version': 'm6-preference-v1', 'rubric_version': 'm6-three-axis-v1',
                             'scenario_source': '当前对话Codex原创设计；不是真实聊天；未生成候选，未审核偏好'})
    return rows


def main():
    path = ROOT / 'data/m6/scenarios.jsonl'
    content = ''.join(json.dumps(row, ensure_ascii=False) + '\n' for row in build())
    if path.exists():
        if path.read_text(encoding='utf-8') != content:
            raise ValueError('已有不同场景文件，拒绝覆盖。')
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding='utf-8')
    print('场景计划：训练180，开发30，最终测试60；尚无模型候选或偏好对。')


if __name__ == '__main__':
    main()
