def write_jsonl(path, rows):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("".join(json.dumps(row, ensure_ascii=False) + "\n" for row in rows), encoding="utf-8")


def main():
    out = ROOT / "data" / "m2"
    if (out / "frozen_manifest.json").exists():
        raise SystemExit("M2 已冻结；不要重建种子数据。修改数据需创建新版本。")
    cards = []
    for category, block in CARDS.items():
        lines = [line.strip() for line in block.strip().splitlines() if line.strip()]
        assert len(lines) == 25, (category, len(lines))
        for i, line in enumerate(lines, 1):
            values = line.split(" | ")
            assert len(values) == 4, line
            cards.append({"family_id": f"train-{category}-{i:02d}", "category": category,
                          "user_variants": values[:3], "assistant": values[3],
                          "source": "project_authored_ai_assisted", "review": "ai_author_checked_human_pending"})
    write_jsonl(out / "raw_cards.jsonl", cards)
    dev = [{"id": f"dev-{i:02d}", "family_id": f"dev-{i:02d}", "category": category,
            "messages": [{"role": "user", "content": user}], "reference_answer": answer,
            "source": "project_authored_ai_assisted"}
           for i, (category, user, answer) in enumerate(DEV, 1)]
    write_jsonl(out / "dev_scenarios.jsonl", dev)
    tests = []
    for category, cases in TEST.items():
        for i, (user, expectation) in enumerate(cases, 1):
            history = []
            if category == "stability" and i == 8:
                history = [{"role": "user", "content": "刚刚我们讨论了代码调试。"},
                           {"role": "assistant", "content": "可以先保留报错，再用最小输入定位问题。"}]
            if category == "stability" and i == 9:
                history = [{"role": "user", "content": "我今天忙得有点乱。"},
                           {"role": "assistant", "content": "先把任务列出来，再选最紧要的一项。"}]
            tests.append({"id": f"test-{category}-{i:02d}", "family_id": f"test-{category}-{i:02d}",
                          "category": category, "messages": history + [{"role": "user", "content": user}],
                          "expectation": expectation, "source": "project_authored_ai_assisted"})
    write_jsonl(ROOT / "data" / "test_scenarios.jsonl", tests)
    print(f"已生成：{len(cards)} 个训练场景族、{len(dev)} 个开发场景、{len(tests)} 个测试场景。")


if __name__ == "__main__":
    main()
